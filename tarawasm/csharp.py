def operation_environment(root: Path) -> dict[str, str]:
    env = os.environ.copy()
    env.update(
        DOTNET_CLI_HOME=str(root / "home"),
        DOTNET_SKIP_FIRST_TIME_EXPERIENCE="1",
        DOTNET_CLI_TELEMETRY_OPTOUT="1",
        DOTNET_NOLOGO="1",
        MSBuildEnableWorkloadResolver="false",
        NUGET_PACKAGES=str(root / "packages"),
    )
    return env


def validate_build_args(args: list[str]) -> None:
    protected = {
        "restorelockedmode",
        "restorepackageswithlockfile",
        "nugetlockfilepath",
        "baseintermediateoutputpath",
        "intermediateoutputpath",
        "baseoutputpath",
        "outputpath",
        "outdir",
        "msbuildprojectextensionspath",
        "nativeintermediateoutputpath",
        "nativeobject",
        "nativebinary",
        "restorepackagespath",
        "nugetpackageroot",
        "publishdir",
        "tarawasmbindingsdir",
        "wasisdkroot",
        "runtimeidentifier",
        "targetframework",
        "assemblyname",
        "restorefallbackfolders",
        "configuration",
        "generatepackageonbuild",
        "publishonbuild",
    }
    index = 0
    while index < len(args):
        arg = args[index]
        if arg.startswith(("-p:", "/p:")):
            name, separator, _ = arg[3:].partition("=")
            if not separator or name.lower() in protected or ";" in arg:
                raise BackendError(
                    f"C# build property '{name}' is managed by tarawasm or malformed."
                )
        elif arg in {"--no-incremental", "--disable-build-servers"}:
            pass
        elif arg in {"-v", "--verbosity"}:
            index += 1
            if index == len(args) or args[index] not in {
                "q",
                "m",
                "n",
                "d",
                "diag",
                "quiet",
                "minimal",
                "normal",
                "detailed",
                "diagnostic",
            }:
                raise BackendError(
                    "C# build requires a verbosity level after --verbosity/-v."
                )
        elif arg.startswith(("--verbosity=", "-v:")):
            level = arg.split("=", 1)[1] if "=" in arg else arg[3:]
            if level not in {
                "q",
                "m",
                "n",
                "d",
                "diag",
                "quiet",
                "minimal",
                "normal",
                "detailed",
                "diagnostic",
            }:
                raise BackendError("Invalid C# build verbosity level.")
        else:
            raise BackendError(
                f"Unsupported C# build argument '{arg}'; use -p:Name=Value, --verbosity, --no-incremental or --disable-build-servers."
            )
        index += 1


def safe_directory(path: Path) -> None:
    for candidate in (path, *path.parents):
        if candidate.is_symlink():
            raise BackendError(f"Refusing symlink in C# artifact path: {candidate}")
    path.mkdir(parents=True, exist_ok=True)


def publish_bindings(staged: Path, root: Path) -> None:
    generated = root / "bindings"
    safe_directory(generated)
    previous = root / "binding-files.json"
    if previous.is_symlink():
        raise BackendError("Refusing symlink C# binding ownership manifest.")
    owned = json.loads(previous.read_text()) if previous.is_file() else []
    if not isinstance(owned, list) or any(
        not isinstance(name, str)
        or Path(name).name != name
        or Path(name).suffix not in {".cs", ".wit"}
        for name in owned
    ):
        raise BackendError("Invalid C# binding ownership manifest.")
    names = [path.name for path in staged.iterdir()]
    for name in set(owned) | set(names):
        path = generated / name
        if (
            path.is_symlink()
            or path.exists()
            and (not path.is_file() or name not in owned)
        ):
            raise BackendError(
                f"Refusing to overwrite unowned or symlink C# binding: {path}"
            )
    for name in names:
        os.replace(staged / name, generated / name)
    for name in set(owned) - set(names):
        (generated / name).unlink(missing_ok=True)
    fd, rendered = tempfile.mkstemp(prefix=".binding-files-", dir=root)
    temporary = Path(rendered)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(json.dumps(names))
        os.replace(temporary, previous)
    finally:
        temporary.unlink(missing_ok=True)


def build_project(
    dotnet: str,
    project: Path,
    wit: Path,
    world: str,
    root: Path,
    output: Path | None,
    tool_args: list[str],
    *,
    binding_only: bool = False,
    validator: str = "wasm-tools",
) -> None:
    require_platform()
    if binding_only:
        if any(arg != "--internal" for arg in tool_args):
            raise BackendError(
                "C# bind accepts --internal after '--'; ABI/output settings are managed by tarawasm."
            )
    else:
        validate_build_args(tool_args)
    if project.suffix != ".csproj" or not project.is_file():
        raise BackendError(
            "C# source/--src must name an existing .csproj; its src/**/*.cs are user sources."
        )
    if not (project.parent / "packages.lock.json").is_file():
        raise BackendError(
            "C# packages.lock.json is missing. Restore it from version control or explicitly run dotnet restore --use-lock-file --force-evaluate before bind/build."
        )
    lock = project.parent / "packages.lock.json"
    if lock.is_symlink():
        raise BackendError("C# packages.lock.json must be a regular project file.")
    safe_directory(root)
    for name in ("obj", "bin", "home", "packages", "bindings"):
        owned_root = root / name
        safe_directory(owned_root)
        for path in owned_root.rglob("*"):
            if path.is_symlink():
                raise BackendError(f"Refusing symlink in C# artifact tree: {path}")
    env = operation_environment(root)
    if (
        run([dotnet, "--version"], env=env, cwd=project.parent).strip()
        != TOOLS["dotnet"]["recommended"]
    ):
        raise BackendError(
            f"C# requires .NET SDK {TOOLS['dotnet']['recommended']}; SDK selection differs from the pinned configuration."
        )
    # NativeAOT's response-file invocation is not quoted upstream. A temporary
    # no-space alias keeps intermediates usable even in projects with spaces.
    with tempfile.TemporaryDirectory(prefix="tarawasm-csharp-") as alias_dir:
        alias = Path(alias_dir) / "work"
        alias.symlink_to(root, target_is_directory=True)
        properties = [
            f"-p:BaseIntermediateOutputPath={alias}/obj/",
            f"-p:BaseOutputPath={alias}/bin/",
            f"-p:TarawasmBindingsDir={alias}/bindings",
            f"-p:WasiSdkRoot={toolchain_home() / 'wasi-sdk'}",
            f"-p:RestoreFallbackFolders={toolchain_home() / 'packages'}",
            "-p:Configuration=Release",
        ]
        lock_before = lock.read_bytes()
        changed = False
        try:
            run(
                [
                    dotnet,
                    "restore",
                    str(project),
                    "--configfile",
                    str(project.parent / "nuget.config"),
                    *properties,
                    "-p:RestoreLockedMode=true",
                ],
                env=env,
                cwd=project.parent,
            )
        finally:
            if not lock.is_file() or lock.read_bytes() != lock_before:
                changed = True
                fd, name = tempfile.mkstemp(
                    prefix=".packages.lock-", dir=project.parent
                )
                with os.fdopen(fd, "wb") as stream:
                    stream.write(lock_before)
                os.replace(name, lock)
        if changed:
            raise BackendError(
                "Locked NuGet restore unexpectedly changed packages.lock.json."
            )
        # Generate in a fresh sibling, replacing only our own binding files.
        with tempfile.TemporaryDirectory(prefix="bindings-", dir=root) as directory:
            staged = Path(directory)
            generate(wit, world, staged, tool_args=tool_args if binding_only else [])
            publish_bindings(staged, root)
        if binding_only:
            return
        with tempfile.TemporaryDirectory(prefix="publish-", dir=root) as directory:
            publish = alias / Path(directory).name
            run(
                [
                    dotnet,
                    "build",
                    str(project),
                    "--no-restore",
                    # Each operation owns its compiler state. Avoid persistent
                    # servers and worker IPC in ephemeral/non-root containers.
                    "--disable-build-servers",
                    "-maxcpucount:1",
                    "-p:BuildInParallel=false",
                    *tool_args,
                    *properties,
                    f"-p:PublishDir={publish}/",
                ],
                env=env,
                cwd=project.parent,
            )
            components = list(Path(directory).glob("*.wasm"))
            if len(components) != 1:
                raise BackendError(
                    "C# build must produce exactly one new publish/*.wasm component."
                )
            if components[0].read_bytes()[:8] != b"\0asm\x0d\0\x01\0":
                raise BackendError(
                    "C# build produced a core module instead of a Component Model component."
                )
            run(
                [validator, "validate", str(components[0])], env=env, cwd=project.parent
            )
            if output is not None:
                shutil.copyfile(components[0], output)


def main(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("action", choices=["bind", "build"])
    parser.add_argument("--dotnet", required=True)
    parser.add_argument("--wasm-tools", default="wasm-tools")
    parser.add_argument("--project", type=Path, required=True)
    parser.add_argument("--wit", type=Path, required=True)
    parser.add_argument("--world", required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    params, trailing = parser.parse_known_args(argv)
    args = trailing[1:] if trailing[:1] == ["--"] else trailing
    if args[-1:] == ["--help"]:
        print(
            run(
                [str(bindgen()), "c-sharp", "--help"]
                if params.action == "bind"
                else [params.dotnet, "build", "--help"]
            )
        )
        return
    build_project(
        params.dotnet,
        params.project,
        params.wit,
        params.world,
        params.root,
        params.output,
        args,
        binding_only=params.action == "bind",
        validator=params.wasm_tools,
    )
