"""Pinned componentize-dotnet integration (also used by managed setup).

Run wit-bindgen as argv: the upstream MSBuild Exec target cannot quote paths.
MSBuild consumes these bindings and their component-type WIT exactly once.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import tempfile
from importlib.resources import files
from pathlib import Path

from tarawasm.backends.base import BackendError
from tarawasm.toolchains.catalog import CATALOG, TOOLS
from tarawasm.toolchains.settings import data_home

VERSIONS = CATALOG["csharp"]
SDK_PACKAGE = "bytecodealliance.componentize.dotnet.wasm.sdk"
BINDGEN_PACKAGE = "bytecodealliance.componentize.dotnet.witbindgen"
LLVM_PACKAGE = "runtime.linux-x64.microsoft.dotnet.ilcompiler.llvm"
PROBE_WIT = """package tarawasm:probe;
world probe { export add: func(left: s32, right: s32) -> s32; }
"""


def require_platform() -> None:
    if platform.system() != "Linux" or platform.machine().lower() not in {
        "x86_64",
        "amd64",
    }:
        raise BackendError(
            "C# NativeAOT-LLVM requires Linux amd64; local C# compilation on "
            f"{platform.system()} {platform.machine()} is unsupported. Select Docker "
            "explicitly: tarawasm toolchain use csharp --mode docker --image <image>. "
            "No execution mode or architecture was changed."
        )


def toolchain_home() -> Path:
    return Path(os.environ.get("TARAWASM_CSHARP_HOME", str(data_home() / "csharp")))


def package_path(name: str) -> Path:
    version = (
        VERSIONS["sdk"] if name in {SDK_PACKAGE, BINDGEN_PACKAGE} else VERSIONS["llvm"]
    )
    return toolchain_home() / "packages" / name / version


def bindgen() -> Path:
    path = package_path(BINDGEN_PACKAGE) / "tools/linux-x64/wit-bindgen"
    if not path.is_file():
        raise BackendError(
            "C# wit-bindgen package missing; run "
            "tarawasm toolchain setup csharp --mode local --install --yes."
        )
    return path


def run(
    argv: list[str],
    *,
    env: dict[str, str] | None = None,
    cwd: Path | None = None,
    timeout: int = 600,
) -> str:
    try:
        result = subprocess.run(
            argv,
            env=env,
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False,
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise BackendError(f"C# tool failed: {argv[0]}: {exc}") from exc
    if result.returncode:
        raise BackendError(
            f"C# tool failed ({result.returncode}): "
            f"{result.stdout}\n{result.stderr}"
        )
    return result.stdout


def generate(
    wit: Path,
    world: str,
    destination: Path,
    *,
    stubs: bool = False,
    tool_args: list[str] | None = None,
) -> None:
    # Keep ABI-affecting options fixed in both bind and build. Extra bindgen
    # options may affect documentation/diagnostics, never the source contract.
    args = tool_args or []
    allowed = {"--internal"}
    if any(arg not in allowed for arg in args):
        raise BackendError(
            "C# bind accepts --internal after '--'; world, runtime, "
            "UTF-8 encoding, result representation, support files and output "
            "are managed by tarawasm."
        )
    run(
        [
            str(bindgen()),
            "c-sharp",
            str(wit),
            "--world",
            world,
            "--runtime",
            "native-aot",
            "--with-wit-results",
            *args,
            *(["--generate-stub"] if stubs else []),
            "--out-dir",
            str(destination),
        ]
    )


def implementation_files(wit: Path, world: str) -> dict[Path, str]:
    require_platform()
    with tempfile.TemporaryDirectory(prefix="tarawasm-csharp-init-") as directory:
        root = Path(directory)
        generate(wit, world, root, stubs=True)
        return {
            Path("src")
            / path.name: path.read_text().replace(
                "// Generated by `wit-bindgen` 0.58.0. DO NOT EDIT!\n// <auto-generated />",
                "// User implementation, initially generated by wit-bindgen 0.58.0.\n"
                "// TODO: replace NotImplementedException bodies with your implementation.",
            )
            for path in root.glob("*Impl.cs")
        }


