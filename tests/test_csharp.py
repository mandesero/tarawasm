@pytest.mark.parametrize("mode", ["directory", "ownership", "dangling", "owned"])
def test_bindings_refuse_symlinks_without_touching_user_files(tmp_path, mode):
    root = tmp_path / "build"
    root.mkdir()
    staged = tmp_path / "staged"
    staged.mkdir()
    (staged / "Api.cs").write_text("new")
    outside = tmp_path / "user"
    outside.mkdir()
    target = outside / "source.cs"
    target.write_text("user")
    bindings = root / "bindings"
    if mode == "directory":
        bindings.symlink_to(outside, target_is_directory=True)
    else:
        bindings.mkdir()
        if mode == "ownership":
            (root / "binding-files.json").symlink_to(target)
        else:
            (bindings / "Api.cs").symlink_to(
                target if mode == "owned" else outside / "missing.cs"
            )
            if mode == "owned":
                (root / "binding-files.json").write_text('["Api.cs"]')
    with pytest.raises(BackendError, match="symlink"):
        csharp.publish_bindings(staged, root)
    assert target.read_text() == "user" and not (outside / "missing.cs").exists()


