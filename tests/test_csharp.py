def test_selected_wasm_validator_runs_before_copying_component(tmp_path, monkeypatch):
    selected = project(tmp_path)
    root = tmp_path / "build"
    output = tmp_path / "previous.wasm"
    output.write_bytes(b"previous")
    monkeypatch.setattr(csharp, "require_platform", lambda: None)
    monkeypatch.setattr(csharp, "generate", lambda *a, **kw: None)
    calls = []

    def run(args, **kwargs):
        calls.append(args)
        if args[1] == "--version":
            return "10.0.402"
        if args[1] == "build":
            assert "--disable-build-servers" in args
            assert "-maxcpucount:1" in args
            publish = Path(
                next(
                    arg.split("=", 1)[1]
                    for arg in args
                    if arg.startswith("-p:PublishDir=")
                )
            )
            (publish / "Component.wasm").write_bytes(b"\0asm\x0d\0\x01\0invalid-code")
        if args[0] == "selected-wasm-tools":
            assert args[1] == "validate"
            raise BackendError("validation failed")
        return ""

    monkeypatch.setattr(csharp, "run", run)
    with pytest.raises(BackendError, match="validation failed"):
        csharp.build_project(
            "dotnet",
            selected,
            tmp_path,
            "calc",
            root,
            output,
            [],
            validator="selected-wasm-tools",
        )
    assert calls[-1][0] == "selected-wasm-tools"
    assert output.read_bytes() == b"previous"


