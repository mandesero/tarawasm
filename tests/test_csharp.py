def test_capability_checks_bindings_version_and_verified_probe(tmp_path, monkeypatch):
    from tarawasm.toolchains import csharp as discovery

    monkeypatch.setattr(csharp, "require_platform", lambda: None)
    monkeypatch.setattr(csharp, "toolchain_home", lambda: tmp_path)
    monkeypatch.setattr(csharp, "bindgen", lambda: tmp_path / "wit-bindgen")
    (tmp_path / "wasi-sdk").mkdir()
    (tmp_path / "wasi-sdk/VERSION").write_text("29.0")
    wasm = b"\0asm\x0d\0\x01\0"
    (tmp_path / "probe.wasm").write_bytes(wasm)
    import hashlib

    receipt = {
        "fingerprint": "verified",
        "component_sha256": hashlib.sha256(wasm).hexdigest(),
    }
    (tmp_path / "capability.json").write_text(json.dumps(receipt))
    monkeypatch.setattr(discovery, "fingerprint", lambda path: "verified")
    monkeypatch.setattr(csharp, "run", lambda *a, **kw: "wit-bindgen 0.58.0")
    assert discovery.capability("dotnet", {})["status"] == "ready"
    monkeypatch.setattr(csharp, "run", lambda *a, **kw: "wit-bindgen 0.62.0")
    assert discovery.capability("dotnet", {})["status"] == "incompatible"
    monkeypatch.setattr(csharp, "run", lambda *a, **kw: "wit-bindgen-cli 0.58.0")
    assert discovery.capability("dotnet", {})["status"] == "ready"
    (tmp_path / "wasi-sdk/VERSION").write_text("")
    assert discovery.capability("dotnet", {})["status"] == "incompatible"
    (tmp_path / "wasi-sdk/VERSION").write_text("29.0")
    (tmp_path / "probe.wasm").write_bytes(b"changed")
    assert discovery.capability("dotnet", {})["status"] == "incompatible"


@pytest.mark.parametrize("missing", ["System.Private.CoreLib.dll", "libc.a"])
def test_capability_fingerprint_rejects_missing_runtime_or_sysroot(
    tmp_path, monkeypatch, missing
):
    from tarawasm.toolchains import csharp as discovery

    monkeypatch.setattr(csharp, "toolchain_home", lambda: tmp_path)
    monkeypatch.setattr(csharp, "bindgen", lambda: tmp_path / "wit-bindgen")
    dotnet = tmp_path / "dotnet"
    paths = discovery.capability_inputs(str(dotnet))
    for path in paths:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"dependency")
    first = discovery.fingerprint(str(dotnet))
    assert first
    selected = next(path for path in paths if path.name == missing)
    selected.unlink()
    with pytest.raises(FileNotFoundError):
        discovery.fingerprint(str(dotnet))


