def test_csharp_dry_run_and_src_out_do_not_create_state(tmp_path, monkeypatch):
    project(tmp_path)
    (tmp_path / "world.wit").write_text(
        "package test:calc; world calc { export add: func() -> u32; }"
    )
    conf = Config(
        "csharp",
        "calc",
        Path("world.wit"),
        "test:calc",
        Path("Component.csproj"),
        Path("dist/calc.wasm"),
        tmp_path / "tarawasm.json",
    )
    conf.save()
    monkeypatch.chdir(tmp_path)
    # Inside-container execution skips host onboarding, as in backend unit tests.
    monkeypatch.setenv("INSIDE_DOCKER", "1")
    before = set(tmp_path.rglob("*"))
    result = CliRunner().invoke(
        cli,
        [
            "build",
            "--src",
            "other project/Other.csproj",
            "--out",
            "out path/result.wasm",
            "--dry-run",
        ],
    )
    assert result.exit_code == 0, result.output
    assert "other project/Other.csproj" in result.output
    assert "out path/result.wasm" in result.output
    assert set(tmp_path.rglob("*")) == before


