def project(tmp_path):
    for name, content in csharp.project_files().items():
        (tmp_path / name).write_text(content)
    return tmp_path / "Component.csproj"


def test_csharp_registration_pins_and_project_inputs(tmp_path):
    assert "csharp" in backend_names() and "csharp" in SUPPORTED_LANGUAGES
    assert set(tools_for("csharp")) == {"dotnet", "wkg", "wasm-tools"}
    files = csharp.project_files()
    assert json.loads(files[Path("global.json")])["sdk"] == {
        "version": "10.0.402",
        "rollForward": "disable",
        "allowPrerelease": False,
    }
    csproj = files[Path("Component.csproj")]
    assert 'Version="[0.8.0-preview00011]"' in csproj
    assert 'Version="[10.0.0-rc.1.26306.1]"' in csproj
    assert '<Wit Remove="@(Wit)"' in csproj
    assert "<RestoreLockedMode>true" in csproj
    assert "<clear />" in files[Path("nuget.config")]
    lock = json.loads(files[Path("packages.lock.json")])
    for deps in lock["dependencies"].values():
        assert all(value.get("contentHash") for value in deps.values())
    conf = Config(
        "csharp",
        "calculator",
        Path("wit"),
        "example:calculator",
        Path("Component.csproj"),
        Path("dist/out.wasm"),
        tmp_path / "tarawasm.json",
    )
    conf.save()
    assert Config.load(tmp_path) == conf


def test_command_paths_src_and_out_are_single_arguments(tmp_path):
    source = tmp_path / "other project/Other.csproj"
    wit = tmp_path / "other wit"
    output = tmp_path / "out path/component.wasm"
    conf = Config(
        "csharp",
        "calc",
        wit,
        "test:calc",
        Path("Component.csproj"),
        output,
        tmp_path / "tarawasm.json",
    )
    backend = get_backend("csharp")
    command = backend.build_command(
        conf,
        world="calc",
        wit=wit,
        source=source,
        output=output,
        tool_args=["-p:DebugSymbols=false"],
    )
    for path in (source, wit, output):
        assert str(path) in command.argv
    assert command.argv[-2:] == ("--", "-p:DebugSymbols=false")
    assert list(tmp_path.iterdir()) == []
    with pytest.raises(BackendError, match=".csproj"):
        backend.build_command(
            conf,
            world="calc",
            wit=wit,
            source=Path("test.cs"),
            output=output,
            tool_args=[],
        )


@pytest.mark.parametrize("absolute", [False, True])
def test_docker_mounts_external_csproj_siblings_readonly(
    tmp_path, monkeypatch, absolute
):
    import click

    from tarawasm.toolchains.runtime import docker_command

    root = tmp_path / "project"
    root.mkdir()
    external = tmp_path / "external project"
    external.mkdir()
    source = external / "Library.csproj"
    source.write_text("<Project />")
    alias = tmp_path / "linked.csproj"
    alias.symlink_to(source)
    conf = Config(
        "csharp",
        "world",
        Path("wit"),
        "test:api",
        Path("Component.csproj"),
        Path("dist/world.wasm"),
        root / "tarawasm.json",
    )
    conf.save()
    monkeypatch.chdir(root)
    context = click.Context(cli.commands["build"], info_name="build")
    context.params = {"source": alias if absolute else Path("../linked.csproj")}
    argv = docker_command(
        {"mode": "docker", "image": "task:csharp"}, "csharp", context, root
    )
    mounted = external if absolute else tmp_path
    assert f"type=bind,source={mounted},target={mounted},readonly" in argv
    assert argv[argv.index("--src") + 1] == (
        str(source) if absolute else "../linked.csproj"
    )
    assert not any("source=/," in value for value in argv)


def test_stub_generation_uses_upstream_and_only_copies_implementations(
    tmp_path, monkeypatch
):
    monkeypatch.setattr(csharp, "require_platform", lambda: None)

    def generate(wit, world, destination, **kwargs):
        assert world == "switch-world" and kwargs == {"stubs": True}
        (destination / "SwitchWorldWorldExportsImpl.cs").write_text(
            "// Generated by `wit-bindgen` 0.58.0. DO NOT EDIT!\n// <auto-generated />\nclass ExactImpl {}"
        )
        (destination / "Bindings.cs").write_text("generated")

    monkeypatch.setattr(csharp, "generate", generate)
    files = csharp.implementation_files(tmp_path, "switch-world")
    assert set(files) == {Path("src/SwitchWorldWorldExportsImpl.cs")}
    assert "DO NOT EDIT" not in next(iter(files.values()))
    assert "User implementation" in next(iter(files.values()))


